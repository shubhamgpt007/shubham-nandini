/* cover.js — scene 1 of 7. "Walk with us."
 *
 * ART        underlay (sky) + base (hotel, gardens, urns) + couple + two sprigs.
 * AMBIENT    sky breathing, sprigs swaying on their edge hinges, the couple shifting
 *            their weight. The BASE never moves: its resting frame is the PSD frame.
 * SIGNATURE  tap the couple -> they take two steps toward the entrance -> complete().
 * FORWARD    "cover-dolly" — the frame pushes in on the porte-cochere and blooms warm
 *            as the next scene settles out of the light.
 *
 * INTRO GATE  this is the scene the curtain intro hands off to — see whenIntroDone().
 *
 * Owns exactly: this file + css/scenes/cover.css.
 */

import * as kit from "../fx/kit.js?v=8";
import * as text from "../fx/text.js?v=9";

/* design-space anchors, read off data/scenes.json / the PSD */
const COUPLE = { x: 306, y: 1206, w: 601, h: 715 };
const HIT_PAD = 72; /* >= 64 design px of slop around the cutout */
const ENTRANCE = [540, 1140]; /* the lit porte-cochere they are walking into */

/* the arrival the intro gate holds back — see playArrival() */
const ARRIVAL_MS = 640;
const ARRIVAL_STEP = 60;

const WALK_MS = 850;
const WALK_RISE = -10; /* design px — they step away from us */
const WALK_SCALE = 0.965;
const DOLLY_MS = 1150;

/* ------------------------------------------------------- the dolly's light
 *
 * The push-in used to carry `filter: brightness(1 -> 1.35) blur(5px)` on the FRAME, and
 * the arriving scene `filter: brightness(1.3 -> 1)` on the whole .scene. Both are the
 * one thing a phone cannot afford at this size (kit.js rule 6): a filter re-renders the
 * node's entire subtree into a fresh offscreen buffer every frame, and the dolly is
 * growing those bounds to 1.16x as it runs — while the ARRIVING scene is asking for a
 * second buffer of its own at the same moment.
 *
 * Both are flat sheets of light now. A childless box with one flat background colour is
 * a solid-colour layer in both engines: the compositor stores the colour, not a bitmap,
 * so these cost no backing store at all. The alphas below are the brightness curves
 * re-solved as `s = (b - 1) * C / (W - C)` against the measured mean of each scene
 * (cover garden ~152 RGB, the names courtyard ~150), then trimmed on the filmstrip.
 */
const DOLLY_TINT = "#fff1d6"; /* the warm porte-cochere light the frame bloomed into */
const DOLLY_A = 0.4; /* peak alpha ~= brightness(1.35) over the cover's daylight */
const ARRIVE_TINT = "#fff4e0";
const ARRIVE_A = 0.34; /* peak alpha ~= brightness(1.3) over the arriving courtyard */

/** A flat sheet of light over `parent`, resting invisible. Solid colour only — no
 *  gradient, no children, no border: that is what keeps it a solid-colour layer. */
function makeSheet(parent, tint, z) {
  if (!parent) return null;
  const s = document.createElement("div");
  s.className = "cv-sheet";
  s.setAttribute("aria-hidden", "true");
  s.style.position = "absolute";
  s.style.inset = "0";
  s.style.zIndex = z;
  s.style.background = tint;
  s.style.opacity = "0";
  s.style.pointerEvents = "none";
  parent.appendChild(s);
  return s;
}

/* One scene instance is ever live, so one module-scope slot is enough. Reset in
   enter(), which the engine replays on every entry. */
let state = null;

/* ---------------------------------------------------------- date cartouche */

/**
 * The rounded-rect frame around the two dates, its two divider rules, and the floral
 * flourish above it.
 *
 * WHY IT LIVES HERE AND NOT IN data/scenes.json
 * ---------------------------------------------
 * data/scenes.json is GENERATED by tools/extract_muskan.py from the FIRST, art-only PSD
 * set. This cartouche exists only in the client's LATER set (~/Downloads/Muskan/Cover
 * Slide.psd), which we deliberately use for text only — so the generator cannot see this
 * element at all, and a layer added to scenes.json by hand would be silently dropped the
 * next time anyone regenerates it. It is scene furniture instead, mounted here with the
 * rest of what this module owns (same pattern as the finale's credit line in last.js).
 *
 * THE ASSET. `assets/fx/date-cartouche.webp` — 2.6KB on the wire, 697x247 -> 672KB
 * decoded, lossless. It is the union box of three layers in that PSD, at their own
 * coordinates: `Rectangle 1` (rounded rect, path 194.96,405.40 -> 886.04,579.60, r38,
 * 3px centre-aligned stroke), `Group 6`'s two rules (paths x 489.30-490.48 and
 * 590.52-591.70, y 437.77-547.23, 2px stroke) and the floral divider smart object.
 * All three are stroke-only (`fill_enabled` false) in #B52645.
 *
 * Rebuilt from those vector paths rather than screen-grabbed: psd-tools paints the
 * disabled fill and rasterises the strokes ~1px thin, so the paths were flattened and
 * stroked at 8x and box-downsampled, which matches the client's own Cover Slide.jpg to
 * within half a design px on every rail. The flourish is raster and came straight out of
 * the PSD untouched.
 *
 * It carries ONLY the ink — the paper behind it is our own underlay wash showing through
 * the transparency, so there is no crop seam to match.
 *
 * NOT part of the engine's image window (js/stage.js snapshots `img.layer` at build
 * time, long before any scene module runs). It does not need to be: the node exists only
 * between enter() and the scene's abort, so its bitmap is held for less time than the
 * window would hold it anyway.
 */
function mountCartouche(ctx) {
  /* revisit: never leave two copies behind */
  ctx.frame.querySelectorAll(".cv-cartouche").forEach(function (n) {
    n.parentNode.removeChild(n);
  });

  const img = document.createElement("img");
  img.className = "cv-cartouche";
  img.src = "assets/fx/date-cartouche.webp?v=2";
  img.alt = "";
  img.setAttribute("aria-hidden", "true");
  img.decoding = "async";
  img.draggable = false;
  ctx.frame.appendChild(img);

  /* Off on the scene's own exit, like every other piece of this scene's furniture.
     Hung on ctx.signal rather than on armInteraction's teardown so it comes off even
     if the gesture never armed (armTap returns early when the couple layer is absent). */
  if (ctx.signal) {
    ctx.signal.addEventListener(
      "abort",
      function () {
        if (img.parentNode) img.parentNode.removeChild(img);
      },
      { once: true }
    );
  }
  return img;
}

/** N&S monogram — pinned to the VIEWPORT top of .scene (frame is offset down by layout). */
const NS_LOGO = {
  src: "assets/scenes/opening/NS-logo.png?v=2",
  width: 248
};

function readCoverFrameScale(frame) {
  if (!frame) return 1;
  const fs = parseFloat(getComputedStyle(frame).getPropertyValue("--fs"));
  if (fs && isFinite(fs) && fs > 0) return fs;
  const w = frame.getBoundingClientRect().width;
  return w > 0 ? w / 1080 : 1;
}

function syncNsLogoLayout(ctx, slot) {
  if (!slot || !slot.isConnected) return;
  const scale = readCoverFrameScale(ctx.frame);
  slot.style.width = Math.round(NS_LOGO.width * scale) + "px";
  slot.style.left = "50%";
  slot.style.top = "50px";
  slot.style.transform = "translateX(-50%)";
}

function mountNsLogo(ctx) {
  ctx.el.querySelectorAll(".cv-ns-logo-slot").forEach(function (n) {
    n.parentNode.removeChild(n);
  });

  const slot = document.createElement("div");
  slot.className = "cv-ns-logo-slot";

  const img = document.createElement("img");
  img.className = "cv-ns-logo";
  img.src = NS_LOGO.src;
  img.alt = "";
  img.setAttribute("aria-hidden", "true");
  img.decoding = "async";
  img.draggable = false;
  slot.appendChild(img);
  ctx.el.appendChild(slot);

  syncNsLogoLayout(ctx, slot);

  var offLayout = null;
  if (ctx.stage && typeof ctx.stage.on === "function") {
    offLayout = ctx.stage.on("layout", function () {
      if (ctx.isActive()) syncNsLogoLayout(ctx, slot);
    });
  }

  img.addEventListener(
    "load",
    function () {
      syncNsLogoLayout(ctx, slot);
    },
    { once: true }
  );
  img.addEventListener(
    "error",
    function () {
      slot.style.display = "none";
    },
    { once: true }
  );

  if (ctx.signal) {
    ctx.signal.addEventListener(
      "abort",
      function () {
        if (offLayout) offLayout();
        if (slot.parentNode) slot.parentNode.removeChild(slot);
      },
      { once: true }
    );
  }
  return slot;
}

/* --------------------------------------------------------------- intro gate */

/**
 * The curtain intro (js/intro.js) owns the screen before this scene is ever seen, so
 * everything that reads exactly ONCE — the artwork's arrival, the copy's reveal, the
 * gesture chip — has to wait for it. Left ungated it would all play out behind an
 * opaque overlay and be over before the guest looked.
 *
 * THE CONTRACT (no engine edit — js/stage.js is not this scene's to touch):
 *   html.intro-active      set inline in index.html's <head>, so it is in force on the
 *                          first frame. css/intro.css uses it to null out the engine's
 *                          entry cascade; this module uses it to know it must wait.
 *   document "intro:done"  dispatched by js/intro.js at the START of its exit fade, not
 *                          at the end. That is the point: everything below runs WHILE
 *                          the curtain dissolves, so the guest sees one crossfade
 *                          rather than a curtain, a pause, and then a scene.
 *
 * With no overlay in the DOM the class is never set and `fn` runs inline, so this scene
 * behaves exactly as it did before the intro existed.
 *
 * `fn` is handed one argument: whether it was actually HELD (true) or ran inline
 * (false). Only the held case may replay the arrival — a guest stepping BACK to this
 * scene later gets the engine's own entry cascade, and re-fading the art on top of it
 * would be a visible second reveal.
 */
function whenIntroDone(ctx, fn) {
  if (!document.documentElement.classList.contains("intro-active")) {
    fn(false);
    return;
  }
  const run = function () {
    document.removeEventListener("intro:done", run);
    if (ctx.isActive()) fn(true);
  };
  document.addEventListener("intro:done", run);
  /* a guest who somehow leaves first must not leave a listener behind */
  if (ctx.signal) {
    ctx.signal.addEventListener(
      "abort",
      function () {
        document.removeEventListener("intro:done", run);
      },
      { once: true }
    );
  }
}

/**
 * The arrival the gate held back: underlay -> base -> layers, fading up in the engine's
 * own order and roughly its own rhythm, landing inside the intro's 1200ms dissolve.
 *
 * OPACITY ONLY, and deliberately so. The engine's cascade (css/stage.css `ms-settle`)
 * also rises 12 design px, but a rise here would read as a JUMP between the clip's last
 * frame and this scene — their skies are nearly the same colour, which is exactly what
 * makes the handoff work, and nearly-identical art sliding 12px is the one thing that
 * would give it away. Staying off `transform` also means the ambient loops can start in
 * the same breath without fighting this for the property.
 *
 * Each animation is cancelled the moment it finishes, so document.getAnimations()
 * returns to zero and nothing is left holding a fill.
 */
function playArrival(ctx) {
  if (ctx.reducedMotion) return;
  const nodes = [
    ctx.el.querySelector(".layer--underlay"),
    ctx.el.querySelector(".layer--base")
  ]
    .concat(Array.prototype.slice.call(ctx.frame.querySelectorAll(".layer--art")))
    /* last in the stagger: the cartouche is drawn ON the paper, so it reads best
       arriving just after the wash it sits on rather than alongside it */
    .concat(Array.prototype.slice.call(ctx.frame.querySelectorAll(".cv-cartouche")))
    .filter(Boolean);

  nodes.forEach(function (node, i) {
    if (typeof node.animate !== "function") return;
    const anim = node.animate([{ opacity: 0 }, { opacity: 1 }], {
      duration: ARRIVAL_MS,
      delay: i * ARRIVAL_STEP,
      easing: "cubic-bezier(0.22, 0.61, 0.36, 1)", /* --ease-out */
      fill: "backwards" /* holds opacity 0 through the delay; no forwards fill to leak */
    });
    const drop = function () {
      try {
        anim.cancel();
      } catch (e) {}
    };
    if (anim.finished && typeof anim.finished.then === "function") {
      anim.finished.then(drop, function () {});
    } else {
      anim.onfinish = drop;
    }
    if (ctx.signal) ctx.signal.addEventListener("abort", drop, { once: true });
  });
}

/* ------------------------------------------------------------------ ambient */

function startAmbient(ctx) {
  const fx = kit.use(ctx);

  /* the sky swells so slowly it reads as air, not animation (never below 1.0, or the
     underlay would pull its own edge into frame) */
  fx.breathe(ctx.el.querySelector(".layer--underlay"), { scale: 1.03, dur: 45000 });

  /* each sprig is hinged on the frame edge it grows in from. The negative amplitude on
     the right one is true antiphase — they lean opposite ways, so the two corners never
     pulse together, and both still start on the resting frame. */
  fx.sway(ctx.layer("sprig-left"), { deg: 1.6, dur: 5500, origin: "0% 18%" });
  fx.sway(ctx.layer("sprig-right"), { deg: -1.6, dur: 6500, origin: "100% 18%", phase: 0.35 });

  /* the couple breathe on the spot until they are asked to move */
  state.bob = fx.bob(ctx.layer("couple"), { px: 3, dur: 3600 });
}

/* -------------------------------------------------------------- interaction */

/** Two bob cycles riding an ease-out to (-10px, 0.965): a walk, not a zoom-out. */
function walkKeyframes() {
  const steps = 8;
  const frames = [];
  for (let i = 0; i <= steps; i += 1) {
    const t = i / steps;
    const ease = 1 - Math.pow(1 - t, 2); /* ease-out on the travel */
    const y = WALK_RISE * ease - 3 * Math.sin(4 * Math.PI * t); /* 2 full bob cycles */
    const s = 1 + (WALK_SCALE - 1) * ease;
    frames.push({
      offset: t,
      transform: "translate3d(0," + y.toFixed(2) + "px,0) scale(" + s.toFixed(4) + ")"
    });
  }
  return frames;
}

function armTap(ctx) {
  const couple = ctx.layer("couple");
  if (!couple) return null;

  /* A real <button> so the gesture is reachable by keyboard and announced to AT.
     Sized from the PSD rect + 72 design px of slop: the cutout is mostly transparent,
     so tapping "near" the couple has to count. */
  const hit = document.createElement("button");
  hit.type = "button";
  hit.className = "cv-hit";
  hit.setAttribute("data-cover-hit", "");
  hit.setAttribute("aria-label", "Walk with Nandini and Shubham");
  hit.style.setProperty("--x", COUPLE.x - HIT_PAD + "px");
  hit.style.setProperty("--y", COUPLE.y - HIT_PAD + "px");
  hit.style.setProperty("--w", COUPLE.w + HIT_PAD * 2 + "px");
  hit.style.setProperty("--h", COUPLE.h + HIT_PAD * 2 + "px");
  ctx.frame.appendChild(hit);

  /* over the couple, at the height where his arm meets her waist: dead centre of the
     two figures, and clear of her head, where the ring would read as marking HER.
     deepesh-bhavna: the forecourt above them is now the Taj Mahal (tools/make_taj_cover.py,
     as krishang-neha), so the pill sits just UNDER the ring, on her skirt, and the
     monument stays clear.

     Built only once the curtain has gone: the chip's own 1.2s appear delay is measured
     from creation, so creating it here-and-now behind the overlay would spend it on an
     empty screen and land the chip the instant the guest first looks. */
  let tip = null;
  whenIntroDone(ctx, function () {
    tip = kit.hint(ctx, {
      designX: 600,
      designY: 1620,
      type: "tap",
      labelAt: [600, 1745]
    });
  });

  const onTap = function () {
    if (!state || state.walking || !ctx.isActive()) return;
    state.walking = true;
    hit.disabled = true;
    if (tip) tip.done();

    const finish = function () {
      if (ctx.isActive()) ctx.complete();
    };

    if (ctx.reducedMotion || typeof couple.animate !== "function") {
      finish();
      return;
    }

    /* stop the idle bob first, or the two would fight over `transform` */
    if (state.bob) {
      state.bob.stop();
      state.bob = null;
    }

    couple.style.transformOrigin = "50% 100%"; /* they shrink toward their own feet */
    const anim = couple.animate(walkKeyframes(), {
      duration: WALK_MS,
      easing: "linear", /* the shape of the walk is IN the keyframes */
      fill: "forwards"
    });

    const handOver = function () {
      /* Bake the stepped-away pose inline and drop the animation in the SAME task: the
         pose survives into the dolly (nothing snaps back on its first frame) and
         document.getAnimations() still returns to zero. enter() clears it on revisit. */
      couple.style.transform =
        "translate3d(0," + WALK_RISE + "px,0) scale(" + WALK_SCALE + ")";
      try {
        anim.cancel();
      } catch (e) {}
      finish();
    };

    if (anim.finished && typeof anim.finished.then === "function") {
      anim.finished.then(handOver, function () {});
    } else {
      anim.onfinish = handOver;
    }
  };

  ctx.on(hit, "click", onTap);

  return function teardown() {
    if (hit.parentNode) hit.parentNode.removeChild(hit);
  };
}

/* ---------------------------------------------------- forward: "cover-dolly" */

/**
 * The camera walks in after them: the outgoing frame pushes toward the entrance and
 * blooms warm, and the next scene settles out of that light.
 *
 * frameZoom composes on top of the layout matrix, so the push-in is expressed in the
 * scene's own design coordinates and survives a resize mid-transition.
 */
kit.defineTransition("cover-dolly", function (fromEl, toEl, done, meta) {
  if (meta.reducedMotion) {
    const anims = [];
    if (fromEl) {
      fromEl.style.zIndex = "2";
      anims.push(fromEl.animate([{ opacity: 1 }, { opacity: 0 }], { duration: 400, fill: "forwards" }));
    }
    toEl.style.zIndex = "1";
    anims.push(toEl.animate([{ opacity: 0 }, { opacity: 1 }], { duration: 400, fill: "backwards" }));
    const t = setTimeout(done, 400);
    return function () {
      clearTimeout(t);
      anims.forEach(function (a) {
        if (a) a.cancel();
      });
      if (fromEl) fromEl.style.zIndex = "";
      toEl.style.zIndex = "";
    };
  }

  let zoom = null;
  const sheets = [];
  const anims = [];

  if (fromEl) {
    fromEl.style.zIndex = "2";
    zoom = kit.frameZoom(fromEl, {
      scale: 1.16,
      originDesign: ENTRANCE,
      dur: DOLLY_MS,
      easing: "cubic-bezier(0.4, 0, 0.2, 1)" /* --ease-bloom */
    });

    /* the bloom the frame's own brightness used to carry. INSIDE the frame, above the
       copy (500), so it lights exactly what the filter lit and is carried by the same
       dolly — the bleed bands outside the frame were never brightened either. */
    const outSheet = makeSheet(fromEl.querySelector(".scene__frame"), DOLLY_TINT, "600");
    if (outSheet) {
      sheets.push(outSheet);
      anims.push(
        outSheet.animate(
          [
            { opacity: 0, offset: 0 },
            { opacity: DOLLY_A * 0.55, offset: 0.6 },
            { opacity: DOLLY_A, offset: 1 }
          ],
          { duration: DOLLY_MS, easing: "cubic-bezier(0.4, 0, 0.2, 1)", fill: "forwards" }
        )
      );
    }

    /* the scene element only dissolves — the push-in lives on its frame */
    anims.push(
      fromEl.animate(
        [
          { opacity: 1, offset: 0 },
          { opacity: 1, offset: 0.42 },
          { opacity: 0, offset: 1 }
        ],
        { duration: DOLLY_MS, easing: "cubic-bezier(0.5, 0, 0.75, 0.5)", fill: "forwards" }
      )
    );
  }

  /* the next scene settles out of that light — the sheet rides INSIDE toEl, so the
     scene's own opacity ramp fades it in exactly as the old filter was faded in */
  toEl.style.zIndex = "1";
  const inSheet = makeSheet(toEl, ARRIVE_TINT, "600");
  if (inSheet) {
    sheets.push(inSheet);
    anims.push(
      inSheet.animate(
        [
          { opacity: ARRIVE_A, offset: 0 },
          { opacity: ARRIVE_A * 0.47, offset: 0.62 },
          { opacity: 0, offset: 1 }
        ],
        { duration: DOLLY_MS, easing: "cubic-bezier(0.22, 0.61, 0.36, 1)", fill: "backwards" }
      )
    );
  }
  anims.push(
    toEl.animate(
      [
        { opacity: 0, transform: "scale(1.035)", offset: 0 },
        { opacity: 0.55, offset: 0.62 },
        { opacity: 1, transform: "scale(1)", offset: 1 }
      ],
      { duration: DOLLY_MS, easing: "cubic-bezier(0.22, 0.61, 0.36, 1)", fill: "backwards" }
    )
  );

  const timer = setTimeout(done, DOLLY_MS);

  return function cleanup() {
    clearTimeout(timer);
    anims.forEach(function (a) {
      if (a) {
        try {
          a.cancel();
        } catch (e) {}
      }
    });
    sheets.forEach(function (n) {
      if (n.parentNode) n.parentNode.removeChild(n);
    });
    if (zoom) zoom.cancel(); /* restores the layout matrix exactly */
    if (fromEl) fromEl.style.zIndex = "";
    toEl.style.zIndex = "";
  };
});

/* ------------------------------------------------------------------ module */

kit.defineScene("cover", {
  forward: "cover-dolly",

  enter: function (ctx) {
    /* the invitation copy, rebuilt from data/textspec.json on every entry */
    text.mount(ctx);
    /* the frame around the dates — scene furniture, not a scenes.json layer */
    mountCartouche(ctx);
    mountNsLogo(ctx);
    state = { bob: null, walking: false };
    /* revisit: no sheet of transition light may survive a previous visit */
    ctx.el.querySelectorAll(".cv-sheet").forEach(function (n) {
      n.parentNode.removeChild(n);
    });
    /* revisit: clear the stepped-away pose the walk baked in, before the first paint */
    const couple = ctx.layer("couple");
    if (couple) {
      couple.style.removeProperty("transform");
      couple.style.removeProperty("transform-origin");
    }
  },

  armInteraction: armTap,

  /* the entry cascade owns `transform` until it finishes, so the copy's reveal and
     the ambient loops both start at idle — and, on the very first view, not until the
     curtain intro hands the screen over (see whenIntroDone) */
  idle: function (ctx) {
    whenIntroDone(ctx, function (heldByIntro) {
      /* only when the gate actually held: on a revisit the engine's own cascade has
         already run and a second fade would read as the scene arriving twice */
      if (heldByIntro) playArrival(ctx);
      text.reveal(ctx); /* before the ambient guards — the copy always shows */
      if (!state || state.walking) return;
      startAmbient(ctx);
    });
  }
});
